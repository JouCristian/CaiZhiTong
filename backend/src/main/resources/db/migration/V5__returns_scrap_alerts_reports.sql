ALTER TABLE stock_transaction ADD CONSTRAINT ck_scrap_link CHECK(txn_type<>'SCRAP' OR scrap_order_id IS NOT NULL);
ALTER TABLE stock_transaction ADD CONSTRAINT ck_single_stock_source CHECK(num_nonnulls(inbound_order_id,issue_order_id,return_order_id,scrap_order_id)=1);
