ALTER TABLE stock_transaction ADD CONSTRAINT fk_tx_scrap_order FOREIGN KEY(scrap_order_id,reference_no) REFERENCES scrap_order(id,scrap_no);
ALTER TABLE stock_transaction ADD CONSTRAINT fk_tx_scrap_batch FOREIGN KEY(scrap_order_id,batch_id) REFERENCES scrap_order(id,batch_id);
