CREATE SEQUENCE return_no_seq MAXVALUE 9999999999 NO CYCLE;
CREATE SEQUENCE scrap_no_seq MAXVALUE 9999999999 NO CYCLE;
CREATE TABLE return_order (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 return_no VARCHAR(32) NOT NULL DEFAULT ('RET-'||lpad(nextval('return_no_seq')::text,10,'0')) UNIQUE,
 issue_order_id BIGINT NOT NULL REFERENCES issue_order(id),
 user_id BIGINT NOT NULL REFERENCES sys_user(id), operator_id BIGINT NOT NULL REFERENCES sys_user(id),
 idempotency_key UUID NOT NULL UNIQUE, request_hash VARCHAR(64) NOT NULL,
 remark VARCHAR(2000), created_at TIMESTAMPTZ NOT NULL,
 UNIQUE(id,issue_order_id), UNIQUE(id,return_no)
);
CREATE TABLE return_order_line (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 return_order_id BIGINT NOT NULL, issue_order_id BIGINT NOT NULL,
 issue_order_line_id BIGINT NOT NULL, batch_id BIGINT NOT NULL,
 quantity NUMERIC(18,3) NOT NULL CHECK(quantity>0), created_at TIMESTAMPTZ NOT NULL,
 FOREIGN KEY(return_order_id,issue_order_id) REFERENCES return_order(id,issue_order_id),
 FOREIGN KEY(issue_order_line_id,batch_id,issue_order_id) REFERENCES issue_order_line(id,batch_id,issue_order_id),
 UNIQUE(return_order_id,issue_order_line_id), UNIQUE(id,batch_id,return_order_id)
);
CREATE TABLE stock_attachment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 storage_key VARCHAR(64) NOT NULL UNIQUE, media_type VARCHAR(40) NOT NULL,
 byte_size BIGINT NOT NULL CHECK(byte_size>0 AND byte_size<=5242880),
 sha256 VARCHAR(64) NOT NULL, uploaded_by BIGINT NOT NULL REFERENCES sys_user(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE scrap_order (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 scrap_no VARCHAR(32) NOT NULL DEFAULT ('SCR-'||lpad(nextval('scrap_no_seq')::text,10,'0')) UNIQUE,
 batch_id BIGINT NOT NULL REFERENCES stock_batch(id),
 quantity NUMERIC(18,3) NOT NULL CHECK(quantity>0),
 reason VARCHAR(1000) NOT NULL CHECK(length(trim(reason))>0), remark VARCHAR(2000),
 attachment_id BIGINT UNIQUE REFERENCES stock_attachment(id),
 operator_id BIGINT NOT NULL REFERENCES sys_user(id),
 idempotency_key UUID NOT NULL UNIQUE, request_hash VARCHAR(64) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL,
 UNIQUE(id,scrap_no), UNIQUE(id,batch_id)
);
