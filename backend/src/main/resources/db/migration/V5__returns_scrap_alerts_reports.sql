CREATE INDEX idx_return_source ON return_order_line(issue_order_line_id);
CREATE INDEX idx_scrap_created ON scrap_order(created_at DESC,id DESC);
CREATE INDEX idx_scrap_batch ON scrap_order(batch_id);
CREATE INDEX idx_issue_course ON issue_order(course);
CREATE TRIGGER immutable_return_order BEFORE UPDATE OR DELETE ON return_order FOR EACH ROW EXECUTE FUNCTION reject_stock_history_change();
CREATE TRIGGER immutable_return_line BEFORE UPDATE OR DELETE ON return_order_line FOR EACH ROW EXECUTE FUNCTION reject_stock_history_change();
CREATE TRIGGER immutable_scrap_order BEFORE UPDATE OR DELETE ON scrap_order FOR EACH ROW EXECUTE FUNCTION reject_stock_history_change();
CREATE TABLE inventory_alert (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 material_id BIGINT NOT NULL REFERENCES material_item(id),
 status VARCHAR(20) NOT NULL CHECK(status IN ('ACTIVE','ACKNOWLEDGED','RESOLVED')),
 level VARCHAR(16) NOT NULL CHECK(level IN ('LOW','CRITICAL')),
 trigger_quantity NUMERIC(28,3) NOT NULL, trigger_safe_stock NUMERIC(18,3) NOT NULL,
 current_quantity NUMERIC(28,3) NOT NULL, current_safe_stock NUMERIC(18,3) NOT NULL,
 material_name VARCHAR(100) NOT NULL, material_code VARCHAR(32) NOT NULL, unit VARCHAR(20) NOT NULL,
 acknowledged_by BIGINT REFERENCES sys_user(id), handling_note VARCHAR(2000),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL, acknowledged_at TIMESTAMPTZ, resolved_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_active_material_alert ON inventory_alert(material_id) WHERE status IN ('ACTIVE','ACKNOWLEDGED');
CREATE INDEX idx_alert_status ON inventory_alert(status,created_at DESC,id DESC);
CREATE TABLE mail_notification (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 alert_id BIGINT NOT NULL UNIQUE REFERENCES inventory_alert(id),
 status VARCHAR(24) NOT NULL CHECK(status IN ('PENDING','NOT_CONFIGURED','SENDING','SENT','FAILED')),
 recipients VARCHAR(4000), attempts INTEGER NOT NULL DEFAULT 0,
 failure_reason VARCHAR(1000), created_at TIMESTAMPTZ NOT NULL, attempted_at TIMESTAMPTZ, sent_at TIMESTAMPTZ
);
CREATE INDEX idx_mail_pending ON mail_notification(status,id);
