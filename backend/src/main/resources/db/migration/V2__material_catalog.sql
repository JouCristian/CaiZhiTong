CREATE TABLE material_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT REFERENCES material_category(id) ON DELETE RESTRICT,
    name VARCHAR(100) NOT NULL CHECK (length(trim(name)) > 0),
    description VARCHAR(2000),
    sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order BETWEEN 0 AND 9999),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_category_not_self CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE UNIQUE INDEX uq_category_sibling_name ON material_category(COALESCE(parent_id, 0), lower(name));
CREATE INDEX idx_category_parent_sort ON material_category(parent_id, sort_order, id);
CREATE SEQUENCE material_code_seq MINVALUE 1 MAXVALUE 9999999999 NO CYCLE;
CREATE TABLE material_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES material_category(id) ON DELETE RESTRICT,
    material_code VARCHAR(32) NOT NULL DEFAULT ('MAT-' || lpad(nextval('material_code_seq')::text, 10, '0')) UNIQUE,
    name VARCHAR(100) NOT NULL CHECK (length(trim(name)) > 0),
    brand VARCHAR(100),
    model VARCHAR(100),
    spec VARCHAR(2000),
    unit VARCHAR(20) NOT NULL CHECK (length(trim(unit)) > 0),
    unit_price NUMERIC(14,4) NOT NULL CHECK (unit_price >= 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'CNY' CHECK (currency ~ '^[A-Z]{3}$'),
    safe_stock NUMERIC(12,3) NOT NULL DEFAULT 0 CHECK (safe_stock >= 0),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','DISABLED','ARCHIVED')),
    description VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_material_category ON material_item(category_id);
CREATE INDEX idx_material_brand_model ON material_item(brand, model);
CREATE INDEX idx_material_created ON material_item(created_at DESC, id DESC);
CREATE INDEX idx_material_status_created ON material_item(status, created_at DESC, id DESC);
COMMENT ON TABLE material_category IS '两层基础类目；品牌与型号为材料属性生成的展示层，不重复维护';
COMMENT ON TABLE material_item IS '材料档案；归档仍保留 ID，后续批次与流水引用本表，库存数量不在档案维护';
COMMENT ON COLUMN material_item.material_code IS '数据库序列生成，稳定唯一，不由客户端指定';

