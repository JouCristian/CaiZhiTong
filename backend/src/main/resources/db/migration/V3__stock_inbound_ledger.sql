CREATE SEQUENCE inbound_order_no_seq MAXVALUE 9999999999 NO CYCLE;
CREATE SEQUENCE stock_batch_code_seq MAXVALUE 9999999999 NO CYCLE;
CREATE SEQUENCE stock_transaction_no_seq MAXVALUE 9999999999 NO CYCLE;
CREATE TABLE inbound_order (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_no VARCHAR(32) NOT NULL DEFAULT ('IN-'||lpad(nextval('inbound_order_no_seq')::text,10,'0')) UNIQUE,
 idempotency_key UUID NOT NULL UNIQUE,
 request_hash VARCHAR(64) NOT NULL,
 created_by BIGINT NOT NULL REFERENCES sys_user(id),
 remark VARCHAR(2000),
 status VARCHAR(16) NOT NULL DEFAULT 'COMPLETED' CHECK (status='COMPLETED'),
 received_at TIMESTAMPTZ NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(id,order_no)
);
CREATE TABLE inbound_order_line (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES inbound_order(id) ON DELETE RESTRICT,
 line_no INTEGER NOT NULL CHECK(line_no>0),
 item_id BIGINT NOT NULL REFERENCES material_item(id) ON DELETE RESTRICT,
 quantity NUMERIC(18,3) NOT NULL CHECK(quantity>0),
 unit_price_snapshot NUMERIC(14,4) NOT NULL CHECK(unit_price_snapshot>=0),
 currency_snapshot VARCHAR(3) NOT NULL CHECK(currency_snapshot ~ '^[A-Z]{3}$'),
 item_code_snapshot VARCHAR(32) NOT NULL,
 item_name_snapshot VARCHAR(100) NOT NULL,
 spec_snapshot VARCHAR(2000),
 unit_snapshot VARCHAR(20) NOT NULL,
 location VARCHAR(100), expire_date DATE, remark VARCHAR(2000),
 UNIQUE(order_id,line_no), UNIQUE(id,item_id)
);
CREATE TABLE stock_batch (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 item_id BIGINT NOT NULL REFERENCES material_item(id) ON DELETE RESTRICT,
 inbound_line_id BIGINT NOT NULL UNIQUE,
 batch_code VARCHAR(32) NOT NULL DEFAULT ('BAT-'||lpad(nextval('stock_batch_code_seq')::text,10,'0')) UNIQUE,
 initial_quantity NUMERIC(18,3) NOT NULL CHECK(initial_quantity>0),
 quantity NUMERIC(18,3) NOT NULL CHECK(quantity>=0 AND quantity<=initial_quantity),
 unit_price_snapshot NUMERIC(14,4) NOT NULL CHECK(unit_price_snapshot>=0),
 received_at TIMESTAMPTZ NOT NULL,
 expire_date DATE, location VARCHAR(100), remark VARCHAR(2000),
 created_by BIGINT NOT NULL REFERENCES sys_user(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(inbound_line_id,item_id) REFERENCES inbound_order_line(id,item_id) ON DELETE RESTRICT
);
CREATE TABLE stock_transaction (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 transaction_no VARCHAR(32) NOT NULL DEFAULT ('TXN-'||lpad(nextval('stock_transaction_no_seq')::text,10,'0')) UNIQUE,
 batch_id BIGINT NOT NULL REFERENCES stock_batch(id) ON DELETE RESTRICT,
 txn_type VARCHAR(10) NOT NULL CHECK(txn_type IN ('IN','OUT','RETURN','SCRAP')),
 qty NUMERIC(18,3) NOT NULL CHECK(qty>0),
 before_quantity NUMERIC(18,3) NOT NULL CHECK(before_quantity>=0),
 after_quantity NUMERIC(18,3) NOT NULL CHECK(after_quantity>=0),
 user_id BIGINT NOT NULL REFERENCES sys_user(id),
 inbound_order_id BIGINT REFERENCES inbound_order(id) ON DELETE RESTRICT,
 reference_no VARCHAR(32) NOT NULL,
 project_no VARCHAR(100), usage VARCHAR(500), remark VARCHAR(2000),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK((txn_type IN ('IN','RETURN') AND after_quantity=before_quantity+qty)
    OR (txn_type IN ('OUT','SCRAP') AND after_quantity=before_quantity-qty)),
 CHECK(txn_type<>'IN' OR inbound_order_id IS NOT NULL),
 FOREIGN KEY(inbound_order_id,reference_no) REFERENCES inbound_order(id,order_no)
);
CREATE UNIQUE INDEX uq_batch_initial_in ON stock_transaction(batch_id) WHERE txn_type='IN';
CREATE INDEX idx_stock_item ON stock_batch(item_id,received_at DESC,id DESC);
CREATE INDEX idx_inbound_created ON inbound_order(created_at DESC,id DESC);
CREATE INDEX idx_line_order ON inbound_order_line(order_id);
CREATE INDEX idx_line_item ON inbound_order_line(item_id);
CREATE INDEX idx_transaction_created ON stock_transaction(created_at DESC,id DESC);
CREATE INDEX idx_transaction_batch ON stock_transaction(batch_id,created_at DESC);
CREATE INDEX idx_transaction_reference ON stock_transaction(reference_no);

CREATE FUNCTION reject_stock_history_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Stock history is append-only' USING ERRCODE='23514'; END $$;
CREATE TRIGGER immutable_inbound_order BEFORE UPDATE OR DELETE ON inbound_order FOR EACH ROW EXECUTE FUNCTION reject_stock_history_change();
CREATE TRIGGER immutable_inbound_line BEFORE UPDATE OR DELETE ON inbound_order_line FOR EACH ROW EXECUTE FUNCTION reject_stock_history_change();
CREATE TRIGGER immutable_stock_transaction BEFORE UPDATE OR DELETE ON stock_transaction FOR EACH ROW EXECUTE FUNCTION reject_stock_history_change();
CREATE FUNCTION protect_batch_origin() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF ROW(NEW.item_id,NEW.inbound_line_id,NEW.batch_code,NEW.initial_quantity,NEW.unit_price_snapshot,NEW.received_at,NEW.created_by,NEW.created_at)
 IS DISTINCT FROM ROW(OLD.item_id,OLD.inbound_line_id,OLD.batch_code,OLD.initial_quantity,OLD.unit_price_snapshot,OLD.received_at,OLD.created_by,OLD.created_at)
 THEN RAISE EXCEPTION 'Batch origin is immutable' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER immutable_batch_origin BEFORE UPDATE ON stock_batch FOR EACH ROW EXECUTE FUNCTION protect_batch_origin();
COMMENT ON TABLE stock_batch IS '库存唯一数量来源，后续扣减采用行锁或 quantity>=delta 条件更新，不直接编辑材料库存';
COMMENT ON TABLE stock_transaction IS '追加式批次流水；本轮仅生成 IN，before/after 为批次余额';
COMMENT ON COLUMN inbound_order.idempotency_key IS '持久唯一请求标识，配合请求摘要和事务锁避免重复入库';

