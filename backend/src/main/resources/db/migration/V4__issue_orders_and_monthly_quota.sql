CREATE SEQUENCE issue_order_no_seq MAXVALUE 9999999999 NO CYCLE;
CREATE TABLE issue_order (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 issue_no VARCHAR(32) NOT NULL DEFAULT ('ISS-'||lpad(nextval('issue_order_no_seq')::text,10,'0')) UNIQUE,
 user_id BIGINT NOT NULL REFERENCES sys_user(id),
 username_snapshot VARCHAR(64) NOT NULL, user_name_snapshot VARCHAR(64) NOT NULL,
 project_no VARCHAR(100) NOT NULL CHECK(length(trim(project_no))>0),
 usage VARCHAR(500) NOT NULL CHECK(length(trim(usage))>0), remark VARCHAR(2000),
 status VARCHAR(16) NOT NULL DEFAULT 'COMPLETED' CHECK(status='COMPLETED'),
 currency VARCHAR(3) NOT NULL CHECK(currency ~ '^[A-Z]{3}$'),
 total_amount NUMERIC(38,7) NOT NULL CHECK(total_amount>=0),
 idempotency_key UUID NOT NULL UNIQUE, request_hash VARCHAR(64) NOT NULL,
 month_start DATE NOT NULL CHECK(extract(day FROM month_start)=1),
 business_zone VARCHAR(80) NOT NULL, created_at TIMESTAMPTZ NOT NULL,
 UNIQUE(id,issue_no)
);
ALTER TABLE stock_batch ADD CONSTRAINT uq_stock_batch_item UNIQUE(id,item_id);
CREATE TABLE issue_order_line (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 issue_order_id BIGINT NOT NULL REFERENCES issue_order(id) ON DELETE RESTRICT,
 line_no INTEGER NOT NULL CHECK(line_no>0),
 material_id BIGINT NOT NULL REFERENCES material_item(id), batch_id BIGINT NOT NULL,
 material_code VARCHAR(32) NOT NULL, material_name VARCHAR(100) NOT NULL,
 spec VARCHAR(2000), unit VARCHAR(20) NOT NULL, batch_code VARCHAR(32) NOT NULL,
 quantity NUMERIC(18,3) NOT NULL CHECK(quantity>0),
 unit_price_snapshot NUMERIC(14,4) NOT NULL CHECK(unit_price_snapshot>=0),
 amount NUMERIC(38,7) NOT NULL CHECK(amount=quantity*unit_price_snapshot),
 created_at TIMESTAMPTZ NOT NULL,
 FOREIGN KEY(batch_id,material_id) REFERENCES stock_batch(id,item_id),
 UNIQUE(issue_order_id,line_no), UNIQUE(issue_order_id,batch_id), UNIQUE(id,batch_id,issue_order_id)
);
CREATE TABLE issue_monthly_usage (
 user_id BIGINT NOT NULL REFERENCES sys_user(id),
 material_id BIGINT NOT NULL REFERENCES material_item(id),
 month_start DATE NOT NULL CHECK(extract(day FROM month_start)=1),
 used_quantity NUMERIC(28,3) NOT NULL DEFAULT 0 CHECK(used_quantity>=0),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,material_id,month_start)
);
