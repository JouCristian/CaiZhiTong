ALTER TABLE sys_user ADD COLUMN password_login_enabled BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE oauth_identity (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 provider VARCHAR(20) NOT NULL CHECK(provider='github'),
 provider_user_id VARCHAR(32) NOT NULL CHECK(provider_user_id ~ '^[1-9][0-9]{0,31}$'),
 user_id BIGINT NOT NULL REFERENCES sys_user(id) ON DELETE RESTRICT,
 provider_login VARCHAR(64) NOT NULL,
 avatar_url VARCHAR(300),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(provider,provider_user_id), UNIQUE(provider,user_id)
);
CREATE TABLE oauth_login_exchange (
 code_hash CHAR(64) PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES sys_user(id) ON DELETE CASCADE,
 verifier_challenge CHAR(43) NOT NULL,
 auth_version BIGINT NOT NULL,
 expires_at TIMESTAMPTZ NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_oauth_exchange_expiry ON oauth_login_exchange(expires_at);
COMMENT ON TABLE oauth_identity IS '稳定 provider ID 唯一关联；不按邮箱或用户名自动关联已有账户';
COMMENT ON TABLE oauth_login_exchange IS '60 秒、哈希存储、浏览器 S256 verifier 绑定的一次性交换码；不存 OAuth Token/JWT';
COMMENT ON COLUMN sys_user.password_login_enabled IS 'OAuth 新账户默认禁用密码入口；管理员明确重置密码后可以开启';
