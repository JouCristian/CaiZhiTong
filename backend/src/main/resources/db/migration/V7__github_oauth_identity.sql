ALTER TABLE sys_user ADD COLUMN password_login_enabled BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE oauth_identity (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 provider VARCHAR(20) NOT NULL CHECK(provider='github'),
 provider_user_id VARCHAR(32) NOT NULL CHECK(provider_user_id ~ '^[1-9][0-9]{0,31}$'),
 user_id BIGINT NOT NULL REFERENCES sys_user(id) ON DELETE RESTRICT,
 provider_login VARCHAR(64) NOT NULL,
 avatar_url VARCHAR(300),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(provider,provider_user_id), UNIQUE(provider,user_id)
);
CREATE TABLE oauth_login_exchange (
 code_hash CHAR(64) PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES sys_user(id) ON DELETE CASCADE,
 verifier_challenge CHAR(43) NOT NULL,
 auth_version BIGINT NOT NULL,
 expires_at TIMESTAMPTZ NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_oauth_exchange_expiry ON oauth_login_exchange(expires_at);
COMMENT ON TABLE oauth_identity IS '稳定 provider ID 唯一关联；不按邮箱或用户名自动关联已有账户';
COMMENT ON TABLE oauth_login_exchange IS '60 秒、哈希存储、浏览器 S256 verifier 绑定的一次性交换码；不存 OAuth Token/JWT';
COMMENT ON COLUMN sys_user.password_login_enabled IS 'OAuth 新账户默认禁用密码入口；管理员明确重置密码后可以开启';

-- Standalone synthetic catalogue. No FK to users, formal materials or business records.
CREATE TABLE demo_category (
 id BIGINT PRIMARY KEY, name VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE demo_material (
 id BIGINT PRIMARY KEY,
 category_id BIGINT NOT NULL REFERENCES demo_category(id),
 material_code VARCHAR(40) NOT NULL UNIQUE,
 name VARCHAR(100) NOT NULL, brand VARCHAR(80) NOT NULL, model VARCHAR(80) NOT NULL,
 spec VARCHAR(300) NOT NULL, unit VARCHAR(20) NOT NULL,
 unit_price NUMERIC(16,4) NOT NULL CHECK(unit_price>=0),
 currency CHAR(3) NOT NULL CHECK(currency IN ('CNY','USD')),
 safe_stock NUMERIC(16,3) NOT NULL CHECK(safe_stock>=0),
 description VARCHAR(500) NOT NULL
);
CREATE INDEX idx_demo_material_category ON demo_material(category_id,id);
CREATE TABLE demo_stock_batch (
 id BIGINT PRIMARY KEY,
 material_id BIGINT NOT NULL REFERENCES demo_material(id),
 batch_code VARCHAR(40) NOT NULL UNIQUE,
 quantity NUMERIC(16,3) NOT NULL CHECK(quantity>=0),
 initial_quantity NUMERIC(16,3) NOT NULL CHECK(initial_quantity>=quantity),
 unit_price NUMERIC(16,4) NOT NULL CHECK(unit_price>=0),
 location VARCHAR(80) NOT NULL, received_on DATE NOT NULL
);
CREATE INDEX idx_demo_batch_material ON demo_stock_batch(material_id,id);
CREATE TABLE demo_stock_event (
 id BIGINT PRIMARY KEY, batch_id BIGINT NOT NULL REFERENCES demo_stock_batch(id),
 event_type VARCHAR(10) NOT NULL CHECK(event_type IN ('IN','OUT')),
 quantity NUMERIC(16,3) NOT NULL CHECK(quantity>0),
 occurred_on DATE NOT NULL, description VARCHAR(200) NOT NULL
);
CREATE INDEX idx_demo_event_batch ON demo_stock_event(batch_id,id);
COMMENT ON TABLE demo_material IS '独立合成公开体验档案，不参与正式库存和报表事务';
COMMENT ON TABLE demo_stock_event IS '无关联人的示例变化，不是正式业务流水';
